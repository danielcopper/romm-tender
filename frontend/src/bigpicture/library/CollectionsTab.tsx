/**
 * The Library page's Collections tab: the kinds on the left, the selected
 * kind's pane on the right.
 *
 * Structure and vocabulary: `docs/architecture/qam-panel.md`, section Library.
 */

import type { FC, ReactNode } from "react";
import { Field, ToggleField } from "@decky/ui";
import { ListDetail, type ListDetailItem } from "../layout/ListDetail";
import {
  MUTED,
  ROW_CONTENT_INSET,
  ROW_MARKER_GAP,
  ROW_MARKER_WIDTH,
  SECONDARY_FONT,
  SELECTION_ACCENT,
} from "../layout/pane";
import {
  KIND_ORDER,
  KIND_TEXT,
  kindMembers,
  onCount,
  resolveFavorites,
  romCountLabel,
  type CollectionsKindId,
  type FavoritesAnswer,
} from "./collectionKinds";
import { CollectionsDetail } from "./CollectionsDetail";
import type { CollectionsPageState } from "./useCollectionsPage";

/** The id of the Autogenerated heading's slot in the list. It is not a kind and
 *  selects nothing: the slot holds text and no stop, so focus never lands on it. */
const AUTOGENERATED_HEADING = "autogenerated-heading";

/** What the Favorites row states in place of a count. */
function favoritesCount(state: CollectionsPageState, favorites: FavoritesAnswer): string {
  if (state.load.state === "failed") return "—";
  if (state.load.state !== "loaded") return "";
  switch (favorites.state) {
    case "one":
      return romCountLabel(favorites.collection.rom_count);
    case "several":
      return "more than one, listed under Collections";
    case "none":
      return "—";
  }
}

function kindCount(state: CollectionsPageState, kind: CollectionsKindId, favorites: FavoritesAnswer): string {
  if (state.load.state === "failed") return "—";
  if (state.load.state !== "loaded") return "";
  return onCount(kindMembers(state.collections, kind, state.ownerScope, favorites));
}

const RowLabel: FC<{ name: string; count: string; selected: boolean }> = ({ name, count, selected }) => (
  <span style={{ display: "flex", alignItems: "baseline", gap: "8px", width: "100%" }}>
    <span
      style={{
        flex: "1 1 auto",
        minWidth: 0,
        overflow: "hidden",
        textOverflow: "ellipsis",
        whiteSpace: "nowrap",
        fontWeight: selected ? 600 : 400,
      }}
    >
      {name}
    </span>
    {/* Allowed to wrap: the unresolved Favorites row states a clause here, not
        a number, and clipping it would leave the reason out. */}
    <span style={{ flex: "0 1 auto", fontSize: SECONDARY_FONT, color: MUTED, textAlign: "right" }}>{count}</span>
  </span>
);

const Marker: FC<{ selected: boolean; children: ReactNode }> = ({ selected, children }) => (
  <div
    style={{
      borderLeft: `${ROW_MARKER_WIDTH}px solid ${selected ? SELECTION_ACCENT : "transparent"}`,
      paddingLeft: `${ROW_MARKER_GAP}px`,
    }}
  >
    {children}
  </div>
);

// Plain text, flush left with the rows indented past it, like the Platforms
// list's group headings.
const GroupHeading: FC<{ title: string }> = ({ title }) => (
  <div
    style={{ padding: "8px 8px 2px", fontSize: SECONDARY_FONT, fontWeight: 600, letterSpacing: "0.5px", color: MUTED }}
  >
    {title.toUpperCase()}
  </div>
);

export const CollectionsTab: FC<{ state: CollectionsPageState }> = ({ state }) => {
  const favorites = resolveFavorites(state.collections);
  const favoritesRow = favorites.state === "one" ? favorites.collection : null;

  const items: ListDetailItem[] = [];
  for (const kind of KIND_ORDER) {
    if (kind === "franchise") {
      items.push({ id: AUTOGENERATED_HEADING, render: () => <GroupHeading title="Autogenerated" /> });
    }
    if (kind === "favorites") {
      items.push({
        id: kind,
        selectOnActivate: favoritesRow === null,
        render: (selected: boolean) => (
          <Marker selected={selected}>
            <div data-testid="kind-row-favorites">
              <ToggleField
                label={
                  <RowLabel
                    name={KIND_TEXT.favorites.name}
                    count={favoritesCount(state, favorites)}
                    selected={selected}
                  />
                }
                checked={favoritesRow?.sync_enabled ?? false}
                disabled={favoritesRow === null}
                bottomSeparator="none"
                onChange={(value: boolean) => {
                  if (favoritesRow) state.toggleCollection(favoritesRow, value, "list");
                }}
              />
            </div>
          </Marker>
        ),
      });
      continue;
    }
    items.push({
      id: kind,
      selectOnActivate: true,
      render: (selected: boolean) => (
        <Marker selected={selected}>
          <div data-testid={`kind-row-${kind}`}>
            <Field
              label={
                <RowLabel name={KIND_TEXT[kind].name} count={kindCount(state, kind, favorites)} selected={selected} />
              }
              bottomSeparator="none"
            />
          </div>
        </Marker>
      ),
    });
  }

  const listHeader: ReactNode = (
    <>
      <div style={{ paddingLeft: `${ROW_CONTENT_INSET}px` }}>
        <ToggleField
          label="Other users' collections"
          description="Their public ones, shown and synced"
          checked={state.ownerScope === "all"}
          bottomSeparator="none"
          onChange={(value: boolean) => state.setOwnerScope(value ? "all" : "own")}
        />
      </div>
      {/* Why the owner switch or the Favorites switch did not take — the two
          writes this column makes. Plain text, and there only while there is
          something to say, so it costs the column no line otherwise. */}
      {state.listStatus && (
        <div
          data-testid="collections-list-status"
          style={{ fontSize: "12px", color: "#dcdedf", padding: `0 0 8px ${ROW_CONTENT_INSET}px` }}
        >
          {state.listStatus}
        </div>
      )}
    </>
  );

  return (
    <ListDetail
      items={items}
      listHeader={listHeader}
      selectedId={state.selectedKind}
      onSelect={state.select}
      renderDetail={() => <CollectionsDetail state={state} favorites={favorites} />}
    />
  );
};
