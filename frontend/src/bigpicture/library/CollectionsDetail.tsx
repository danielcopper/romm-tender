/**
 * One kind's pane on the Library page's Collections tab: what the kind is, what
 * turning one of its collections on does, a search with Enable all and Disable
 * all beside it, and the kind's collections as a table.
 *
 * Every row of the table is a toggle, so A works it and the row is reachable
 * through it; the table's header and the line under its last row are text that
 * scrolls with the rows.
 *
 * Structure and vocabulary: `docs/architecture/qam-panel.md`, section Library.
 */

import type { CSSProperties, FC } from "react";
import { ConfirmModal, DialogButton, TextField, ToggleField, showModal } from "@decky/ui";
import { LoadingRow } from "../LoadingRow";
import {
  ButtonRow,
  CELL_CLIP,
  FLAT_BUTTON,
  MUTED,
  Muted,
  PANE_GUTTER,
  PaneTableHeader,
  SECONDARY_FONT,
} from "../layout/pane";
import {
  KIND_TEXT,
  hiddenForeignCount,
  inSteamLabel,
  kindSentence,
  ownerLabel,
  romCountLabel,
  type CollectionsKindId,
  type FavoritesAnswer,
} from "./collectionKinds";
import { shownCollections, type CollectionsPageState } from "./useCollectionsPage";
import type { CollectionSyncSetting } from "../../types";

/** How many rows the table paints. The autogenerated kinds run to hundreds, and
 *  painting them all strains Steam's renderer; the search narrows below it,
 *  and Enable all / Disable all reach past it. */
export const COLLECTION_RENDER_CAP = 50;

// The label's columns, and the one more the header has over the toggle a row
// draws at its right edge.
const OWNED_COLUMNS = "minmax(0, 1fr) 72px 40px 52px";
const OWNERLESS_COLUMNS = "minmax(0, 1fr) 40px 52px";
const SYNC_TRACK = "52px";

const NUMBER: CSSProperties = { textAlign: "right" };

const Title: FC<{ kind: CollectionsKindId }> = ({ kind }) => (
  <div style={{ display: "flex", alignItems: "baseline", gap: "10px", padding: `8px ${PANE_GUTTER} 2px` }}>
    <span style={{ fontSize: "16px", fontWeight: 600, color: "#dcdedf" }}>{KIND_TEXT[kind].name}</span>
    <span style={{ fontSize: SECONDARY_FONT, color: MUTED }}>{KIND_TEXT[kind].about}</span>
  </div>
);

const Sentence: FC<{ text: string }> = ({ text }) => (
  <div
    data-testid="collections-sentence"
    style={{ fontSize: SECONDARY_FONT, color: "#dcdedf", padding: `0 ${PANE_GUTTER} 6px` }}
  >
    {text}
  </div>
);

/** What stands in place of the table, or of the Favorites count, while the
 *  listing is not there: a spinner, or why it did not come. */
const LoadState: FC<{ state: CollectionsPageState }> = ({ state }) => {
  if (state.load.state === "failed") {
    return (
      <div data-testid="collections-load-failed">
        <Muted>{state.load.message ?? "Could not read your collections from RomM."}</Muted>
        <Muted>Leave this tab and come back to ask again.</Muted>
      </div>
    );
  }
  return <LoadingRow />;
};

const FavoritesPane: FC<{ state: CollectionsPageState; favorites: FavoritesAnswer }> = ({ state, favorites }) => {
  const name = favorites.state === "one" ? favorites.collection.name : undefined;
  let body;
  if (state.load.state !== "loaded") body = <LoadState state={state} />;
  else if (favorites.state === "one")
    body = <Muted>{`Games in it: ${romCountLabel(favorites.collection.rom_count)}`}</Muted>;
  else if (favorites.state === "several")
    body = (
      <Muted>
        More than one favorites collection counts as yours, so the Favorites switch cannot stand for them. They are
        listed under Collections, each with its own switch.
      </Muted>
    );
  else body = <Muted>Your RomM account has no favorites collection.</Muted>;
  return (
    <>
      <Title kind="favorites" />
      <Sentence text={kindSentence("favorites", name)} />
      {body}
    </>
  );
};

const CollectionRow: FC<{ collection: CollectionSyncSetting; owned: boolean; state: CollectionsPageState }> = ({
  collection,
  owned,
  state,
}) => {
  const number = { ...CELL_CLIP, ...NUMBER, fontSize: SECONDARY_FONT };
  return (
    <div style={{ padding: `0 ${PANE_GUTTER}` }} data-testid="collection-row">
      <ToggleField
        label={
          <span
            style={{
              display: "grid",
              gridTemplateColumns: owned ? OWNED_COLUMNS : OWNERLESS_COLUMNS,
              gap: "8px",
              width: "100%",
              alignItems: "baseline",
            }}
          >
            <span style={CELL_CLIP} title={collection.name}>
              {collection.name}
            </span>
            {owned && (
              <span style={{ ...CELL_CLIP, fontSize: SECONDARY_FONT, color: MUTED }} data-testid="collection-owner">
                {ownerLabel(collection)}
              </span>
            )}
            <span style={number} data-testid="collection-roms">
              {collection.rom_count}
            </span>
            <span style={number} data-testid="collection-in-steam">
              {inSteamLabel(collection)}
            </span>
          </span>
        }
        checked={collection.sync_enabled}
        bottomSeparator="none"
        onChange={(value: boolean) => state.toggleCollection(collection, value, "pane")}
      />
    </div>
  );
};

function confirmSetAll(state: CollectionsPageState, kind: CollectionsKindId, count: number, enabled: boolean) {
  const name = KIND_TEXT[kind].name;
  const past =
    count > COLLECTION_RENDER_CAP ? `, including those past the first ${COLLECTION_RENDER_CAP} the table shows` : "";
  const reach = `This switches ${count === 1 ? "the one collection" : `all ${count} collections`} listed under ${name}${past}.`;
  showModal(
    <ConfirmModal
      strTitle={enabled ? `Enable all ${count} in ${name}?` : `Disable all ${count} in ${name}?`}
      strDescription={
        enabled
          ? `${reach} Their games come to Steam with the next sync, including games on platforms you do not sync.`
          : reach
      }
      strOKButtonText={enabled ? "Enable all" : "Disable all"}
      strCancelButtonText="Cancel"
      onOK={() => state.setAllShown(enabled)}
    />,
  );
}

const KindPane: FC<{
  state: CollectionsPageState;
  kind: Exclude<CollectionsKindId, "favorites">;
  favorites: FavoritesAnswer;
}> = ({ state, kind, favorites }) => {
  const owned = KIND_TEXT[kind].owned;
  const loaded = state.load.state === "loaded";
  const shown = loaded ? shownCollections(state) : [];
  const rendered = shown.slice(0, COLLECTION_RENDER_CAP);
  const overflow = shown.length - rendered.length;
  const canWrite = shown.length > 0;
  // A search is what makes the write a bounded subset the reader can see; with
  // none it is the whole kind, which is asked about first on every kind.
  const setAll = (enabled: boolean) => {
    if (state.search === "") confirmSetAll(state, kind, shown.length, enabled);
    else state.setAllShown(enabled);
  };

  let body;
  if (!loaded) body = <LoadState state={state} />;
  else if (shown.length === 0) {
    const hidden = hiddenForeignCount(state.collections, kind, state.ownerScope, favorites);
    body = (
      <>
        <Muted>
          {state.search === ""
            ? `Nothing to list under ${KIND_TEXT[kind].name}.`
            : `Nothing under ${KIND_TEXT[kind].name} matches the search.`}
        </Muted>
        {state.search === "" && hidden > 0 && (
          <Muted>{`${hidden} from other users ${hidden === 1 ? "is" : "are"} hidden while Other users' collections is off.`}</Muted>
        )}
      </>
    );
  } else {
    body = (
      <>
        <PaneTableHeader
          columns={`${owned ? OWNED_COLUMNS : OWNERLESS_COLUMNS} ${SYNC_TRACK}`}
          cells={[
            "Collection",
            ...(owned ? ["Owner"] : []),
            { content: "ROMs", style: NUMBER },
            { content: "In Steam", style: NUMBER },
            { content: "Sync", style: NUMBER },
          ]}
        />
        {rendered.map((collection) => (
          <CollectionRow
            key={`${collection.kind}:${collection.id}`}
            collection={collection}
            owned={owned}
            state={state}
          />
        ))}
        {overflow > 0 && <Muted>{`${overflow} more — refine the search to reach them.`}</Muted>}
      </>
    );
  }

  return (
    <>
      <Title kind={kind} />
      <Sentence text={kindSentence(kind)} />
      <ButtonRow padding={`0 ${PANE_GUTTER} 6px`}>
        {/* The word beside the field rather than above it or inside it: a
            heading costs the pane a line, and `TextFieldProps` declares no
            placeholder. */}
        <span style={{ flex: "0 0 auto", alignSelf: "center", fontSize: SECONDARY_FONT, color: MUTED }}>Search</span>
        <div style={{ flex: "1 1 auto", minWidth: 0 }}>
          <TextField value={state.search} onChange={(e) => state.setSearch(e.target.value)} />
        </div>
        <DialogButton style={{ ...FLAT_BUTTON, flex: "0 0 auto" }} disabled={!canWrite} onClick={() => setAll(true)}>
          Enable all
        </DialogButton>
        <DialogButton style={{ ...FLAT_BUTTON, flex: "0 0 auto" }} disabled={!canWrite} onClick={() => setAll(false)}>
          Disable all
        </DialogButton>
      </ButtonRow>
      {/* Why a table write did not take, under the controls that make the
          bigger of them and above the rows they change. Present only while
          there is something to say. */}
      {state.paneStatus && (
        <div
          data-testid="collections-pane-status"
          style={{ fontSize: "12px", color: "#dcdedf", padding: `0 ${PANE_GUTTER} 8px` }}
        >
          {state.paneStatus}
        </div>
      )}
      {body}
    </>
  );
};

export const CollectionsDetail: FC<{ state: CollectionsPageState; favorites: FavoritesAnswer }> = ({
  state,
  favorites,
}) => {
  const kind = state.selectedKind;
  if (kind === "favorites") return <FavoritesPane state={state} favorites={favorites} />;
  return <KindPane state={state} kind={kind} favorites={favorites} />;
};
